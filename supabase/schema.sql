create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now()
);
alter table public.messages enable row level security;
-- Public visitors may submit messages only. Do not grant public SELECT access.
drop policy if exists "Anyone can submit contact messages" on public.messages;
create policy "Anyone can submit contact messages" on public.messages for insert to anon, authenticated with check (true);
